import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import YAML from 'yaml';
import { PNG } from 'pngjs';
import { SimulatorRunLifecycle } from './simulator-run-lifecycle.mjs';
import { startupCommand } from './simulator-startup.mjs';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'run8-budgets-'));
try {
  let now = 0;
  const state = new SimulatorRunLifecycle(dir, { now: () => now, ciDeadlineMs: Infinity });
  assert.equal(state.remaining(), 600000);
  for (const invalid of [0, -1, NaN, Infinity]) assert.throws(() => state.enterPhase('invalid', invalid), /finite and positive/);
  now = 590000;
  state.enterPhase('startup:rotation-preflight', 120000);
  assert.equal(state.remaining(), 120000);
  now += 119000;
  state.enterPhase('install', 300000);
  assert.equal(state.remaining(), 300000);
  now += 299000;
  state.enterPhase('startup:unified-log-readiness', 120000);
  assert.equal(state.remaining(), 120000);
  now += 119000;
  state.enterPhase('startup:native-capture-build', 120000);
  assert.equal(state.remaining(), 120000);
  now += 119000;
  state.enterPhase('startup:native-capture-readiness', 240000);
  assert.equal(state.remaining(), 240000);
  now += 239000;
  for (let i = 1; i <= 7; i++) {
    state.line(`[KINESYNC_SIM] STAGE_BEGIN stage_${i}_test`);
    assert.equal(state.remaining(), 120000);
    now += 119000;
  }
  const deadline = state.deadline;
  state.line('[KINESYNC_SIM] STAGE_BEGIN stage_8_complete');
  assert.equal(state.deadline, deadline, 'Completion is not an eighth 120-second scenario');
  now = deadline;
  assert.throws(() => state.line('[KINESYNC_SIM] STAGE_BEGIN unknown'), /timeout/);
  assert.throws(() => state.enterPhase('late install', 300000), /timeout/, 'An expired phase cannot renew its clock');
  const expired = new SimulatorRunLifecycle(path.join(dir, 'expired'), { now: () => 100, ciDeadlineMs: 99, command: () => { throw Error('must not spawn'); } });
  expired.device = 'fake'; expired.capture(); expired.cleanup();
  const skipped = fs.readFileSync(path.join(expired.outputDir, 'startup-commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  assert.ok(skipped.every(r => /deadline exhausted/.test(r.error.message)), 'Evidence/cleanup must preserve the overall ceiling');
  const real = new SimulatorRunLifecycle(path.join(dir, 'real'), { ciDeadlineMs: Infinity });
  const eof = `process.stdin.resume(); process.stdin.on('end', () => { console.log('EOF received'); console.error('success stderr'); });`;
  assert.match(await startupCommand(process.execPath, ['-e', eof], real, undefined, 2000), /EOF received/);
  await assert.rejects(startupCommand(process.execPath, ['-e', `console.log('partial stdout'); console.error('partial stderr'); setInterval(() => {}, 1000)`], real, undefined, 2000), error => error.killed);
  await assert.rejects(startupCommand(process.execPath, ['-e', `console.log('failed stdout'); console.error('failed stderr'); process.exit(7)`], real), error => error.code === 7);
  const ledger = fs.readFileSync(path.join(real.outputDir, 'startup-commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  for (const [i, expected] of ['success stderr', 'partial stderr', 'failed stderr'].entries()) {
    assert.match(fs.readFileSync(path.join(real.outputDir, ledger[i].stderr), 'utf8'), new RegExp(expected));
    assert.ok(ledger[i].ended >= ledger[i].started);
  }
  assert.equal(ledger[0].exitCode, 0);
  assert.equal(ledger[1].error.signal, 'SIGKILL');
  assert.equal(ledger[2].exitCode, 7);
  assert.match(fs.readFileSync(path.join(real.outputDir, ledger[1].stdout), 'utf8'), /partial stdout/);
  const png = PNG.sync.write(new PNG({ width: 2, height: 3 }));
  const pngPath = path.join(real.outputDir, 'timed-out.png');
  const writePNG = `require('fs').writeFileSync(process.argv.at(-1), Buffer.from(${JSON.stringify([...png])})); console.log('PNG saved'); setInterval(() => {}, 1000);`;
  await assert.rejects(startupCommand(process.execPath, ['-e', writePNG, 'screenshot', pngPath], real, undefined, 2000), error => error.killed);
  assert.equal(PNG.sync.read(fs.readFileSync(pngPath)).height, 3);
  const last = fs.readFileSync(path.join(real.outputDir, 'startup-commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse).at(-1);
  assert.equal(last.error.signal, 'SIGKILL');
  assert.equal(last.png, undefined, 'A valid PNG cannot turn a timed-out command into success');
  await assert.rejects(startupCommand(process.execPath, ['-e', '', 'screenshot', pngPath], real), /ENOENT/);
  assert.ok(!fs.existsSync(pngPath), 'A stale PNG cannot satisfy a successful command that writes nothing');
  await startupCommand(process.execPath, ['-e', 'process.stdout.write(Buffer.from([255, 0, 127])); process.stderr.write(Buffer.from([254, 1]));'], real);
  const binary = fs.readFileSync(path.join(real.outputDir, 'startup-commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse).at(-1);
  assert.deepEqual([...fs.readFileSync(path.join(real.outputDir, binary.stdout))], [255, 0, 127]);
  assert.deepEqual([...fs.readFileSync(path.join(real.outputDir, binary.stderr))], [254, 1]);
  const workflow = YAML.parse(fs.readFileSync(new URL('../../.github/workflows/ios-simulator-test.yml', import.meta.url), 'utf8'));
  const job = workflow.jobs['ios-simulator-test'];
  const steps = job.steps;
  const native = workflow.jobs['native-apps'];
  assert.equal(native['timeout-minutes'], 120);
  assert.equal(job['timeout-minutes'], 55);
  assert.match(native.steps.find(s => s.name === 'Select and verify installed toolchain').run, /85 \* 60 \* 1000/);
  assert.match(steps.find(s => s.name === 'Record job work start').run, /45 \* 60 \* 1000/);
  assert.match(steps.find(s => s.id === 'scenario').run, /--timeout-minutes 40/);
  assert.equal(steps.find(s => s.id === 'scenario')['timeout-minutes'], 40);
  assert.deepEqual(job.strategy.matrix.variant, ['candidate', 'baseline']);
  assert.ok(job.needs.includes('native-apps'));
  assert.equal(600 + 120 + 300 + 120 + 120 + 240 + 7 * 120, 39 * 60);
  assert.equal(40 * 60 - (600 + 120 + 300 + 120 + 120 + 240 + 7 * 120), 60);
  assert.equal(workflow.jobs.diagnostic['timeout-minutes'], 20);
  assert.match(workflow.jobs.resolve.if, /diagnostic_only != 'true'/);
  assert.equal(workflow.jobs.resolve.outputs.candidate, '${{ steps.refs.outputs.candidate }}');
  console.log('Independent phase budgets, subprocess EOF/raw logs, and workflow reserve tests passed.');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
