"use strict";

const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const ROOT = path.resolve(__dirname, "../..");
const SHARED_FILE = path.join(ROOT, "DesktopBridge/src/musixmatchProfile.js");
const MOBILE_FILE = path.join(ROOT, "ExpoLyrics/lib/mobile-lyrics-service.js");
const PROFILE_FILE = path.join(ROOT, "ExpoLyrics/lib/musixmatch-profile.js");
const PARTS = [
  { file: "02-network-and-spotify.js", names: ["MUSIXMATCH_CLIENT_PROFILES"],
    before: { MUSIXMATCH_CLIENT_PROFILES: ["MUSIXMATCH_APP_MOBILE_PROFILE"] } },
  { file: "05a-musixmatch-client.js", names: [
    "normalizeMusixmatchBody",
    "buildMusixmatchProfileForAppId", "extractMusixmatchMatchedTrack", "extractMusixmatchSubtitleBody",
    "assertMusixmatchSuccess", "shouldAbortMusixmatchTokenAttempt", "resolveMusixmatchClientCandidates", "fetchMusixmatchJson",
  ], after: { appendMusixmatchSignature: ["fetchMusixmatchText"], normalizeMusixmatchBody: ["redactMusixmatchDiagnostic"] } },
  { file: "05b-musixmatch-parsing.js", names: [
    "buildMusixmatchMatcherQueries", "fetchMusixmatchTrackCandidates", "fetchMusixmatchRichsyncForCandidate",
    "fetchMusixmatchSubtitleForCandidate", "fetchFromMusixmatch",
  ], after: { extractMusixmatchCandidateIdentity: ["extractMusixmatchRecordingIsrc", "buildMusixmatchResultMetadata", "parseMusixmatchSubtitleLyrics"] } },
];

function declarationRanges(source, fileName) {
  const ast = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  if (ast.parseDiagnostics.length) throw new Error(`Cannot parse ${fileName}; refusing partial sync.`);
  const found = new Map();
  const add = (name, node, declarationCount = 1) => {
    const ranges = found.get(name) || [];
    ranges.push({ start: node.getStart(ast), end: node.end, declarationCount });
    found.set(name, ranges);
  };
  const visit = (node) => {
    if (ts.isFunctionDeclaration(node) && node.name) add(node.name.text, node);
    if (ts.isVariableStatement(node)) {
      for (const declaration of node.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name)) add(declaration.name.text, node, node.declarationList.declarations.length);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(ast);
  return found;
}

function oneRange(declarations, name, label) {
  const matches = declarations.get(name) || [];
  if (matches.length !== 1 || matches[0].declarationCount !== 1) {
    throw new Error(`Expected one standalone declaration of ${name} in ${label}.`);
  }
  return matches[0];
}

function segmentRange(mobile, file) {
  const marker = `// ---- DesktopBridge/src/lyrics/parts/${file} ----`;
  const markerAt = mobile.indexOf(marker);
  if (markerAt < 0 || mobile.indexOf(marker, markerAt + marker.length) >= 0) {
    throw new Error(`Expected one mobile section marker for ${file}.`);
  }
  const start = markerAt + marker.length;
  const end = mobile.indexOf("\n// ---- DesktopBridge/src/lyrics/parts/", start);
  if (end < 0) throw new Error(`Missing next section marker after ${file}.`);
  return { start, end };
}

function profileText(sharedSource) {
  const declarations = declarationRanges(sharedSource, "musixmatchProfile.js");
  const names = ["MUSIXMATCH_APP_MOBILE_PROFILE", "isUsableMusixmatchToken"];
  return "// Generated by scripts/sync-musixmatch-core.cjs. Edit DesktopBridge/src/musixmatchProfile.js.\n" +
    names.map((name) => { const range = oneRange(declarations, name, "shared profile"); return sharedSource.slice(range.start, range.end); }).join("\n\n") +
    `\n\nexport { ${names.join(", ")} };\n`;
}

function renewalCallRange(source) {
  const ast = ts.createSourceFile("source-scoring.js", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const declarations = declarationRanges(source, "source-scoring.js");
  const wrapper = oneRange(declarations, "invokeSourceFetcher", "source-scoring.js");
  const calls = [];
  const visit = (node) => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "refreshMusixmatchUserToken" &&
        node.getStart(ast) >= wrapper.start && node.end <= wrapper.end) {
      calls.push({ start: node.getStart(ast), end: node.end });
    }
    ts.forEachChild(node, visit);
  };
  visit(ast);
  if (calls.length !== 1) throw new Error("Expected one Musixmatch renewal call inside invokeSourceFetcher.");
  return calls[0];
}

function syncText(mobile, readPart, sharedSource = fs.readFileSync(SHARED_FILE, "utf8")) {
  const sharedDecls = declarationRanges(sharedSource, "musixmatchProfile.js");
  const replacements = [];
  for (const part of PARTS) {
    const section = segmentRange(mobile, part.file);
    const targetText = mobile.slice(section.start, section.end);
    const desktop = readPart(part.file);
    const targetDecls = declarationRanges(targetText, `mobile-${part.file}`);
    const sourceDecls = declarationRanges(desktop, part.file);
    const newNames = Object.values({ ...part.before, ...part.after }).flat();
    const allNames = [...part.names, ...newNames];
    for (const name of allNames) {
      const shared = name === "MUSIXMATCH_APP_MOBILE_PROFILE";
      const source = oneRange(shared ? sharedDecls : sourceDecls, name, part.file);
      const sourceText = (shared ? sharedSource : desktop).slice(source.start, source.end);
      const targets = targetDecls.get(name) || [];
      if (!targets.length) {
        if (!newNames.includes(name)) throw new Error(`Missing ${name} in mobile ${part.file}.`);
        continue;
      }
      if (targets.length > 1 && !newNames.includes(name)) throw new Error(`Duplicate ${name} in mobile ${part.file}.`);
      if (targets.some((target) => target.declarationCount !== 1)) throw new Error(`Non-standalone ${name} in mobile ${part.file}.`);
      replacements.push({ start: section.start + targets[0].start, end: section.start + targets[0].end, text: sourceText });
      // Canonicalize only generator-owned helpers if a previously interrupted sync duplicated them.
      for (const duplicate of targets.slice(1)) {
        let end = duplicate.end;
        while (targetText[end] === "\n") end++;
        replacements.push({ start: section.start + duplicate.start, end: section.start + end, text: "" });
      }
    }
    for (const [placement, anchors] of [["before", part.before], ["after", part.after]]) {
      for (const [anchorName, names] of Object.entries(anchors || {})) {
        const missing = names.filter((name) => !targetDecls.has(name));
        if (!missing.length) continue;
        const anchor = oneRange(targetDecls, anchorName, `mobile ${part.file}`);
        const text = missing.map((name) => {
          const shared = name === "MUSIXMATCH_APP_MOBILE_PROFILE";
          const range = oneRange(shared ? sharedDecls : sourceDecls, name, part.file);
          return (shared ? sharedSource : desktop).slice(range.start, range.end);
        }).join("\n\n");
        const at = section.start + (placement === "before" ? anchor.start : anchor.end);
        replacements.push({ start: at, end: at, text: placement === "before" ? `${text}\n\n` : `\n\n${text}` });
      }
    }
  }
  const scoringFile = "07a-source-scoring.js";
  const section = segmentRange(mobile, scoringFile);
  const target = renewalCallRange(mobile.slice(section.start, section.end));
  const source = readPart(scoringFile);
  const sourceCall = renewalCallRange(source);
  replacements.push({ start: section.start + target.start, end: section.start + target.end,
    text: source.slice(sourceCall.start, sourceCall.end) });
  replacements.sort((a, b) => b.start - a.start || b.end - a.end);
  let output = mobile;
  for (const replacement of replacements) output = output.slice(0, replacement.start) + replacement.text + output.slice(replacement.end);
  return output;
}

function generate({ check = false } = {}) {
  const sharedSource = fs.readFileSync(SHARED_FILE, "utf8");
  const mobile = fs.readFileSync(MOBILE_FILE, "utf8");
  const outputs = [
    [MOBILE_FILE, syncText(mobile, (file) => fs.readFileSync(path.join(ROOT, "DesktopBridge/src/lyrics/parts", file), "utf8"), sharedSource)],
    [PROFILE_FILE, profileText(sharedSource)],
  ];
  const changed = outputs.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);
  if (check && changed.length) throw new Error("Mobile Musixmatch declarations are out of sync; run npm run sync:musixmatch.");
  if (!check) for (const [file, text] of changed) fs.writeFileSync(file, text);
  return changed.length > 0;
}

function preservationFingerprint(mobile) {
  const edits = [];
  for (const part of PARTS) {
    const section = segmentRange(mobile, part.file);
    const declarations = declarationRanges(mobile.slice(section.start, section.end), part.file);
    const owned = [...part.names, ...Object.values({ ...part.before, ...part.after }).flat()];
    for (const name of owned) for (const range of declarations.get(name) || []) {
      edits.push({ start: section.start + range.start, end: section.start + range.end, text: "" });
    }
  }
  const scoring = segmentRange(mobile, "07a-source-scoring.js");
  const call = renewalCallRange(mobile.slice(scoring.start, scoring.end));
  edits.push({ start: scoring.start + call.start, end: scoring.start + call.end, text: "__musixmatch_renewal_call__" });
  let unowned = mobile;
  for (const edit of edits.sort((a, b) => b.start - a.start)) unowned = unowned.slice(0, edit.start) + edit.text + unowned.slice(edit.end);
  // New standalone declarations can add blank separators. Preserve every other source line exactly,
  // including comments, string literals, adapters, and the rest of invokeSourceFetcher.
  const lines = unowned.split(/\r?\n/).filter((line) => !/^\s*$/.test(line)).join("\n");
  return require("node:crypto").createHash("sha256").update(lines).digest("hex");
}

if (require.main === module) {
  try { console.log(generate({ check: process.argv.includes("--check") }) ? "Synchronized mobile Musixmatch declarations." : "Mobile Musixmatch declarations are synchronized."); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { PARTS, syncText, profileText, declarationRanges, renewalCallRange, preservationFingerprint };
